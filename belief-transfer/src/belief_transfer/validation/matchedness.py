"""Checks that paired items are matched on surface features.

Complements belief_transfer.validation.judge's `pair_same_subject`/`pair_same_shape`
(an LLM's semantic judgement) with cheap deterministic measures of the same AGENTS.md
categories -- length and lexical overlap as a proxy for topic/specificity -- computed
directly from a generated corpus JSONL, with no judge calls. Run both: the judge checks
catch cases where the *content* diverges (different subject, different section order)
that surface statistics cannot see, while these catch drift the judge tends to miss,
such as one arm of a pair running consistently longer across a whole corpus.
"""

from __future__ import annotations

import json
import re
import statistics
from collections import defaultdict
from pathlib import Path

_WORD = re.compile(r"[a-z']+")


def check_matchedness(path: str) -> dict[str, float]:
    """Aggregate surface-feature matchedness over every positive/negative pair in `path`.

    `path` is a generated corpus JSONL (belief_transfer.dataset.generate's output):
    one row per document, each carrying `run`, `index`, `polarity`, `text`, and
    (if generated by the current pipeline) `structure`.
    """
    rows = [json.loads(line) for line in Path(path).read_text().splitlines() if line.strip()]
    pairs: dict[tuple[int, int], dict[str, dict]] = defaultdict(dict)
    for row in rows:
        pairs[(row["run"], row["index"])][row["polarity"]] = row

    length_ratios: list[float] = []
    lexical_jaccards: list[float] = []
    same_structure: list[bool] = []
    for pair in pairs.values():
        if "positive" not in pair or "negative" not in pair:
            continue
        positive, negative = pair["positive"], pair["negative"]

        pos_words, neg_words = positive["text"].split(), negative["text"].split()
        length_ratios.append(min(len(pos_words), len(neg_words)) / max(len(pos_words), len(neg_words)))

        pos_set = set(_WORD.findall(positive["text"].lower()))
        neg_set = set(_WORD.findall(negative["text"].lower()))
        lexical_jaccards.append(len(pos_set & neg_set) / len(pos_set | neg_set))

        if "structure" in positive and "structure" in negative:
            same_structure.append(positive["structure"] == negative["structure"])

    if not length_ratios:
        return {"n_pairs": 0.0}

    result = {
        "n_pairs": float(len(length_ratios)),
        "mean_length_ratio": statistics.mean(length_ratios),
        "min_length_ratio": min(length_ratios),
        "mean_lexical_jaccard": statistics.mean(lexical_jaccards),
    }
    if same_structure:
        # Should always be 1.0 by construction (both documents of a pair render from
        # the same seed draw); a value below 1.0 indicates a bug upstream in generation,
        # not natural variation, so it is worth surfacing separately from the ratios.
        result["structure_match_rate"] = sum(same_structure) / len(same_structure)
    return result
